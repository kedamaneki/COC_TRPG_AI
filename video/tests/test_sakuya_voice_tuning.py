from __future__ import annotations

import json
import unittest
from pathlib import Path

from video_agent.voice.sakuya_voice_tuning import (ANONYMOUS_ASSIGNMENT, FIXTURE_LINES,
    TUNING_PROFILE_IDS, TUNING_RATES, resolve_anonymous_selection,
    validate_approved_selection, validate_tuning_profiles)
from video_agent.voice.yukkuri_voice_compat import playback_filter


ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent


class SakuyaVoiceTuningTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        document = json.loads((ROOT / "config/voice_profiles.json").read_text(encoding="utf-8"))
        cls.profiles = {item["voice_profile_id"]: item for item in document["profiles"]}

    def test_candidate_contract(self):
        self.assertEqual([], validate_tuning_profiles(self.profiles))
        self.assertEqual((120, 115, 110, 105), TUNING_RATES)

    def test_human_selection_resolves_from_manifest(self):
        manifest = json.loads((REPO / "fixtures/sakuya_voice_tuning/anonymous_mapping_manifest.json").read_text(encoding="utf-8"))
        self.assertEqual(("sakuya_tune_110_v1", 110), resolve_anonymous_selection(self.profiles, manifest, "A"))
        self.assertEqual([], validate_approved_selection(self.profiles, manifest, "A"))

    def test_only_playback_rate_varies(self):
        candidates = [self.profiles[TUNING_PROFILE_IDS[rate]] for rate in TUNING_RATES]
        self.assertEqual({"f1"}, {item["voice_type"] for item in candidates})
        self.assertEqual({105}, {item["reading_speed"] for item in candidates})
        self.assertEqual({50.0}, {item["source_volume_percent"] for item in candidates})
        self.assertEqual({105.0, 110.0, 115.0, 120.0}, {item["playback_rate_percent"] for item in candidates})

    def test_pitch_and_speed_remain_coupled(self):
        for rate in TUNING_RATES:
            value = playback_filter(self.profiles[TUNING_PROFILE_IDS[rate]], 8000)
            self.assertIn("asetrate=", value)
            self.assertNotIn("atempo", value)

    def test_selected_profile_cache_identity_fields_are_required(self):
        source = (ROOT / "src/video_agent/rendering/pipeline.py").read_text(encoding="utf-8")
        for field in ("voice_profile_id", "source_text", "voice_type", "reading_speed",
                      "playback_rate_percent", "source_volume_percent"):
            self.assertIn(f'"{field}"', source)

    def test_anonymous_assignment_is_bijective(self):
        self.assertEqual({"A", "B", "C", "D"}, set(ANONYMOUS_ASSIGNMENT))
        self.assertEqual(set(TUNING_RATES), set(ANONYMOUS_ASSIGNMENT.values()))

    def test_active_mapping_is_unchanged(self):
        registry = json.loads((ROOT / "config/character_registry.json").read_text(encoding="utf-8"))
        sakuya = next(item for item in registry["characters"] if item["character_id"] == "sakuya")
        self.assertEqual("sakuya_tune_110_v1", sakuya["voice_profile_id"])

    def test_fixture_contains_all_three_lines_and_candidates(self):
        manifest_path = REPO / "fixtures/sakuya_voice_tuning/technical_manifest.json"
        if not manifest_path.exists():
            self.skipTest("fixture is generated by the build tool")
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        self.assertEqual(12, len(manifest["records"]))
        self.assertEqual(set(FIXTURE_LINES), {item["line_id"] for item in manifest["records"]})
        for item in manifest["records"]:
            measurement = item["measurement"]
            self.assertEqual(48000, measurement["sample_rate"])
            self.assertEqual(1, measurement["channels"])
            self.assertEqual(64, len(measurement["sha256"]))
            self.assertIsNotNone(measurement["integrated_lufs"])


if __name__ == "__main__":
    unittest.main()

